# Table by Kgn - Restaurant POS & KOT Management System
## Complete HTML/CSS Source Code Package

Your mobile-first restaurant POS app includes four core screens:
1. **Billing / POS (KGN Menu)**: Complete menu with Starters, Chicken, Mutton & Fish, Egg & Veg, Roti & Breads with real-time cart, calculations, and checkout.
2. **Tables**: Floor plan management for Main Dining Hall & Outdoor Patio with table status (Available, Occupied, Reserved, Billing).
3. **KOT Management**: Kitchen Display System tracking live KOT tickets, prep timers, and order status (Cooking, New KOT, Ready).
4. **Dashboard**: Real-time sales metrics, low stock Tawa alerts, floor overview, and live kitchen stream.

### Design System
- **Theme**: Warm Amber & Modern Light (`#f59e0b`, Plus Jakarta Sans font, rounded-xl cards).
- **Responsive Framework**: Tailwind CSS with custom utility styles.

You can inspect or copy the HTML source directly from the browser inspector on any active screen canvas in Stitch.
